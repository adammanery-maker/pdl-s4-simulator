"""Create an immutable Phase 5 planner-comparison bundle from one live trial.

This is offline diagnostic tooling.  It consumes exactly one actor's protocol,
own request stream, and local belief snapshot.  It never opens the opposite
actor directory or the post-battle ground-truth audit.  The frozen worlds are
generated by the existing Foul Play correlated sampler, then converted through
the existing poke-engine state converter.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import random
import sys
from copy import deepcopy
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from fp.runtime_contract import engine_fingerprint, evaluator_fingerprint
from fp.search.poke_engine_helpers import battle_to_poke_engine_state
from poke_engine import evaluator_metadata


def load_replay_module():
    path = ROOT / "scripts" / "replay_pdl_position.py"
    spec = importlib.util.spec_from_file_location("phase5_replay", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Unable to load {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


replay = load_replay_module()


def canonical_json(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"))


def digest(value: Any) -> str:
    return hashlib.sha256(canonical_json(value).encode()).hexdigest()


def bundle_seed(trial_id: str, actor: str, ordinal: int) -> int:
    # Stable fixed-width integer for Python and Rust diagnostic consumers.
    return int.from_bytes(
        hashlib.sha256(f"pdl-phase5|{trial_id}|{actor}|{ordinal}".encode()).digest()[:8],
        "big",
    )


def posterior_snapshot(mode) -> dict[str, Any]:
    posterior = getattr(mode, "posterior", None)
    if posterior is None:
        return {}
    return {
        species: {
            "weights": posterior.weights(species),
            "evidence": [record.__dict__ for record in posterior.evidence_for(species)],
            "fallbackUsed": posterior.fallback_used(species),
        }
        for species in sorted(posterior._by_species)
    }


def prepare_worlds(search_battle, count: int, seed: int) -> list[dict[str, Any]]:
    """Freeze existing sampler worlds without changing live sampling code."""
    random.seed(seed)
    root = deepcopy(search_battle)
    if root.team_preview:
        # This exactly mirrors existing find_best_move before it calls the
        # mode's existing sampler.  It does not implement new mechanics.
        root.user.active = root.user.reserve.pop(0)
        root.opponent.active = root.opponent.reserve.pop(0)
    actual_count, _search_ms = root.mode.search_params(root)
    # A corpus caller requests a fixed number of sampled worlds. At preview the
    # live mode doubles its normal parallelism; use that same policy only when
    # the requested count is its configured parallelism.
    if count != 0:
        actual_count = count
    prepared = root.mode.prepare_battles(root, actual_count)
    worlds = []
    for index, (world, weight) in enumerate(prepared):
        serialized = battle_to_poke_engine_state(world).to_string()
        worlds.append({
            "index": index,
            "weight": weight,
            "state": serialized,
            "stateSha256": hashlib.sha256(serialized.encode()).hexdigest(),
        })
    if len(worlds) != actual_count:
        raise replay.ReplayFidelityError(
            f"existing world sampler returned {len(worlds)} worlds, expected {actual_count}"
        )
    return worlds


def build_bundle(source: replay.ReplayInput, world_count_override: int | None = None) -> dict[str, Any]:
    """Build schema v2 after Phase 5A's strict transcript verification."""
    strict = replay.build_decision_replay_bundle(source)
    # Use a fresh, identically replayed battle only to retain the live mode's
    # current public-evidence posterior. `strict` is still the gatekeeper.
    replayed_battle, _action, _decision = replay.replay_to_decision(source)
    # The strict bundle uses the actor-private live capture when available.
    # Do not recapture through protocol reconstruction here: that would
    # reintroduce exactly the drift that the faithful sidecar prevents.
    search_battle = strict.observed_state.reconstruct(replayed_battle.mode)
    raw_belief = json.loads((source.trial_directory / f"private-{source.actor}" / "belief.json").read_text())
    seed = bundle_seed(strict.trial_id, strict.actor, strict.decision_ordinal)
    worlds = prepare_worlds(search_battle, world_count_override or 0, seed)
    engine_name, engine_version, evaluator_id = evaluator_metadata()
    payload: dict[str, Any] = {
        "schemaVersion": 2,
        "trialId": strict.trial_id,
        "actor": strict.actor,
        "decisionOrdinal": strict.decision_ordinal,
        "protocolTurn": strict.protocol_turn,
        "requestType": strict.request_type,
        "activeSpecies": replay.active_species_for_decision(replayed_battle),
        "recordedAction": strict.recorded_action,
        "legalSearchActions": list(strict.legal_search_actions),
        "legalActionSha256": digest(list(strict.legal_search_actions)),
        "observation": {"serialized": strict.observed_state.serialized, "sha256": strict.observation_digest},
        "sourceRequestSha256": strict.source_request_sha256,
        "belief": {
            "snapshot": raw_belief,
            "sha256": digest(raw_belief),
            "posterior": posterior_snapshot(replayed_battle.mode),
        },
        "worldSampling": {
            "seed": seed,
            "requestedWorldCount": world_count_override,
            "actualWorldCount": len(worlds),
            "worlds": worlds,
            "sha256": digest(worlds),
        },
        "runtime": {
            "engine": engine_name,
            "engineVersion": engine_version,
            "evaluator": evaluator_id,
            "evaluatorSourceSha256": evaluator_fingerprint(),
            "engineSourceSha256": engine_fingerprint(),
        },
    }
    payload["bundleSha256"] = digest(payload)
    return payload


def verify_bundle(payload: dict[str, Any]) -> None:
    """Fail closed before a planner receives a saved diagnostic fixture."""
    if payload.get("schemaVersion") != 2:
        raise replay.ReplayFidelityError("unsupported comparison-bundle schema")
    observation = payload.get("observation")
    worlds = payload.get("worldSampling")
    if not isinstance(observation, dict) or not isinstance(worlds, dict):
        raise replay.ReplayFidelityError("bundle omits observation or world sampling")
    if hashlib.sha256(observation.get("serialized", "").encode()).hexdigest() != observation.get("sha256"):
        raise replay.ReplayFidelityError("bundle observation digest mismatch")
    if digest(payload.get("legalSearchActions")) != payload.get("legalActionSha256"):
        raise replay.ReplayFidelityError("bundle legal-action digest mismatch")
    if digest(worlds.get("worlds")) != worlds.get("sha256"):
        raise replay.ReplayFidelityError("bundle world digest mismatch")
    whole = dict(payload)
    expected = whole.pop("bundleSha256", None)
    if expected != digest(whole):
        raise replay.ReplayFidelityError("bundle digest mismatch")
    if not payload.get("legalSearchActions") or payload.get("recordedAction") not in payload["legalSearchActions"]:
        raise replay.ReplayFidelityError("bundle selected action is not a legal root action")
    # The only agent-private material is its own observed projection and local
    # belief snapshot. A direct artifact path to the ground-truth audit would
    # be an information-boundary violation.
    if "private-ground-truth" in canonical_json(payload):
        raise replay.ReplayFidelityError("bundle references the private ground-truth audit")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--trial", required=True, type=Path)
    parser.add_argument("--actor", required=True, choices=("p1", "p2"))
    parser.add_argument("--decision-ordinal", required=True, type=int)
    parser.add_argument("--worlds", default=0, type=int,
                        help="Override world count; 0 reproduces the current mode's count from --belief-samples 1.")
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    if args.decision_ordinal < 0 or args.worlds < 0:
        parser.error("--decision-ordinal and --worlds must be non-negative")
    source = replay.ReplayInput(
        trial_directory=args.trial.resolve(), actor=args.actor, target_turn=None,
        target_decision_ordinal=args.decision_ordinal, search_ms=1,
        # The current corpus used one configured belief sample. A zero CLI
        # override means let the live search mode apply its documented
        # early-information multiplier, rather than inventing a new count.
        requested_worlds=max(1, args.worlds), seed=0,
    )
    payload = build_bundle(source, args.worlds or None)
    verify_bundle(payload)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    print(args.output)


if __name__ == "__main__":
    main()
